                .createShader(r));
      final p = Paint()
        ..color = Colors.white
        ..strokeWidth = 2
        ..strokeCap = StrokeCap.round;
      final c = r.center;
      canvas.drawLine(c - const Offset(8, 0), c + const Offset(8, 0), p);
      canvas.drawLine(c - const Offset(0, 8), c + const Offset(0, 8), p);
      return;
    }
    canvas.scale(size.width / 26, size.height / 26);
