        ..strokeJoin = StrokeJoin.round;
      if (page == 0) canvas.drawPath(home, homePaint);
      // Keep the exterior bounds identical, including the outline thickness.
      canvas.drawPath(home, homePaint..style = PaintingStyle.stroke);
      return;
    }
    // Reuse one canonical outline and one selected glyph per destination.
    // Per-page crops included an incorrect square for Home on the chat tab.
    const selectedPaths = [0, 5, 0, 14, 19];
    const outlinePaths = [8, 1, 0, 2, 3];
    final pathIndex = page == item ? selectedPaths[item] : outlinePaths[item];
    canvas.drawPath(
        paths[pathIndex],
        Paint()
          ..color = (page == item
              ? const Color(0xFF191919)
              : const Color(0xFF909090)));
  }

